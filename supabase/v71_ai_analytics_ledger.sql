-- NOVATEK admin dashboard: AI usage analytics ledger only.
-- This migration intentionally does NOT reset or alter existing Smart Compare quotas.
create table if not exists public.ai_usage_events (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid references auth.users(id) on delete set null,
  feature text not null default 'smart_compare',
  provider text not null default 'unknown',
  model text,
  status text not null check (status in ('success','failed','cached')),
  latency_ms integer,
  input_tokens integer,
  output_tokens integer,
  total_tokens integer,
  cost_usd numeric(12,8),
  cost_is_estimate boolean not null default true,
  compared_product_ids jsonb not null default '[]'::jsonb,
  error_code text
);
create index if not exists ai_usage_events_created_at_idx on public.ai_usage_events(created_at desc);
create index if not exists ai_usage_events_user_id_idx on public.ai_usage_events(user_id, created_at desc);
create index if not exists ai_usage_events_provider_idx on public.ai_usage_events(provider, created_at desc);
alter table public.ai_usage_events enable row level security;
revoke all on public.ai_usage_events from anon, authenticated;
grant select, insert, update, delete on public.ai_usage_events to service_role;
grant usage, select on sequence public.ai_usage_events_id_seq to service_role;
notify pgrst, 'reload schema';
